#!/usr/bin/env python3
"""Generate optional HomeGenie scripting references from Doxygen XML (stdlib only)."""
import argparse
import html
import re
import sys
from pathlib import Path
import xml.etree.ElementTree as ET


TOPICS = {
    "modules": ("Module selection and values", ["ModulesManager", "ModuleHelper", "Module", "ModuleParameter", "ValueStatistics", "StatValue"]),
    "programs": ("Program lifecycle and configuration", ["ProgramHelper", "ProgramHelperBase"]),
    "events": ("Events and scheduler", ["EventsHelper", "SchedulerHelper"]),
    "storage": ("Data, settings and store", ["DataHelper", "SettingsHelper", "StoreHelper"]),
    "network": ("HTTP and local API calls", ["NetHelper", "ApiHelper"]),
    "protocols": ("MQTT, KNX, TCP, UDP and serial", ["MqttClientHelper", "KnxClientHelper", "TcpClientHelper", "UdpClientHelper", "SerialPortHelper"]),
}


def text(node):
    return " ".join("".join(node.itertext()).split()) if node is not None else ""


def prose(node):
    """Keep descriptions; omit old code examples, parameter lists and source listings."""
    if node is None or node.tag in {"programlisting", "parameterlist", "xrefsect"}:
        return ""
    if node.tag == "simplesect" and node.get("kind") not in {"return", "warning", "note"}:
        return ""
    return (node.text or "") + "".join(prose(child) + (child.tail or "") for child in node)


def signature(member):
    kind = member.get("kind")
    prefix = "static " if member.get("static") == "yes" else ""
    result = prefix + text(member.find("type")) + " " + member.findtext("name")
    if kind == "function":
        result += text(member.find("argsstring"))
    elif kind == "property":
        access = [name + ";" for name in ("get", "set") if member.get(name + "table") == "yes"]
        result += " { " + " ".join(access) + " }" if access else ""
    return result.strip()


def load_classes(xml_dir):
    index = ET.parse(xml_dir / "index.xml").getroot()
    wanted = {name for _, names in TOPICS.values() for name in names}
    classes = {}
    for entry in index.findall("compound"):
        full_name = entry.findtext("name", "")
        name = full_name.split("::")[-1]
        if entry.get("kind") != "class" or name not in wanted:
            continue
        if not full_name.startswith(("HomeGenie::Automation::Scripting::", "HomeGenie::Data::", "HomeGenie::ProgramHelperBase")):
            continue
        compound = ET.parse(xml_dir / (entry.get("refid") + ".xml")).find("compounddef")
        if name in classes:
            raise ValueError("Ambiguous scripting class: " + name)
        classes[name] = compound
    missing = wanted - classes.keys()
    if missing:
        raise ValueError("Incomplete Doxygen XML; missing: " + ", ".join(sorted(missing)))
    return classes


def render(xml_dir):
    classes = load_classes(xml_dir)
    result = {}
    index = ["# HomeGenie scripting API reference index", "",
             "Generated from Doxygen XML. These are backend automation APIs, not widget JavaScript APIs or a device-command inventory.", "",
             "Load only the required topic with the HomeGenie prompt composer. Links alone do not load a reference; dynamic model-driven retrieval is not implemented.", "",
             "Keep the shared automation.md rules loaded. Use the host-provided Program, Modules, Events, Scheduler, Data, Settings, Net and Api objects; do not construct helpers or ProgramHelperBase.", ""]
    for topic, (title, names) in TOPICS.items():
        filename = "api-" + topic + ".md"
        index += [f"- [{title}]({filename}): {', '.join(names)}.",
                  f"  Include: `#use-kb homegenie-core/references/{filename}`"]
        lines = ["# " + title, "", "Generated by generate-ai-api-reference.py from Doxygen XML. Do not edit by hand.", "",
                 "C# signatures below describe backend automation APIs. Python/JavaScript use hg. accessors. Follow automation.md for lifecycle, iteration and type rules. Constructors and implementation-only classes are excluded. Undocumented public members are listed by signature only; do not infer behavior from their names.", ""]
        for name in names:
            compound = classes[name]
            lines += ["## " + name, ""]
            bases = [text(base).replace("::", ".") for base in compound.findall("basecompoundref") if base.get("prot") == "public"]
            if bases:
                lines += ["Inherits: " + ", ".join(bases) + ". Inherited members are listed under the base class.", ""]
            members = [m for m in compound.findall("sectiondef/memberdef")
                       if m.get("prot") == "public" and m.get("kind") in {"function", "property", "variable", "event"}
                       and m.findtext("name") not in {name, "~" + name}]
            for member in sorted(members, key=lambda m: (m.findtext("name"), signature(m))):
                lines += ["```csharp", signature(member), "```"]
                # Examples are deliberately excluded: source examples are reviewed separately.
                for tag in ("briefdescription", "detaileddescription"):
                    description = html.unescape(" ".join(prose(member.find(tag)).split())).replace("\\n", " ")
                    description = re.sub(r"\s*Example:\s*$", "", description)
                    if description and description != "Example:":
                        lines += [description]
                for param in member.findall("detaileddescription//parameterlist[@kind='param']/parameteritem"):
                    lines += ["- " + text(param.find("parameternamelist")) + ": " + text(param.find("parameterdescription"))]
                lines += [""]
        result[filename] = "\n".join(lines).rstrip() + "\n"
    result["api-index.md"] = "\n".join(index).rstrip() + "\n"
    return result


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--xml-dir", type=Path, required=True)
    parser.add_argument("--output-dir", type=Path, required=True)
    parser.add_argument("--check", action="store_true", help="Fail if checked-in references differ; write nothing.")
    args = parser.parse_args()
    try:
        documents = render(args.xml_dir)
        stale = []
        for filename, content in documents.items():
            target = args.output_dir / filename
            if args.check:
                if not target.exists() or target.read_text(encoding="utf-8") != content:
                    stale.append(filename)
            else:
                args.output_dir.mkdir(parents=True, exist_ok=True)
                target.write_text(content, encoding="utf-8", newline="\n")
        if stale:
            parser.error("References need regeneration: " + ", ".join(stale))
        print(f"{'Checked' if args.check else 'Generated'} {len(documents)} scripting API references.")
    except (OSError, ET.ParseError, ValueError) as exc:
        print("API reference generation failed: " + str(exc), file=sys.stderr)
        return 1
    return 0


if __name__ == "__main__":
    sys.exit(main())
